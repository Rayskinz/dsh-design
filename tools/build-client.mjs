// Builds lib/client.js from src/client.src.js by inlining src/games.js.
// The app loads the browser half as one classic script (no imports), so the tested
// game rules are wrapped in a function scope and pasted in at the /*@games*/ marker.
// Run: node tools/build-client.mjs        (npm run build)
// Check: node tools/build-client.mjs --check   (exit 1 if lib/client.js is stale)
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

export function buildClient() {
  const src = fs.readFileSync(path.join(root, 'src', 'client.src.js'), 'utf8').replace(/\r\n/g, '\n')
  // Every rule module is wrapped in its own function scope and its exports are re-declared once, so a
  // clash between two modules is a loud build error instead of a silent override.
  const MODULES = ['games.js', 'games2.js', 'fx.js', 'family.js']
  const seen = new Map()
  const parts = []
  MODULES.forEach((file, i) => {
    const p = path.join(root, 'src', file)
    if (!fs.existsSync(p)) return
    const code = fs.readFileSync(p, 'utf8').replace(/\r\n/g, '\n')
    const names = [...code.matchAll(/^export (?:const|function|let) ([A-Za-z0-9_$]+)/gm)].map((m) => m[1])
    if (names.length === 0) throw new Error(`no exports found in src/${file}`)
    for (const name of names) {
      if (seen.has(name)) throw new Error(`export "${name}" is declared in both src/${seen.get(name)} and src/${file}`)
      seen.set(name, file)
    }
    const body = code.replace(/^export /gm, '')
    parts.push(`const M${i} = (() => {\n${body}\nreturn { ${names.join(', ')} };\n})();\nconst { ${names.join(', ')} } = M${i};`)
  })
  if (parts.length === 0) throw new Error('no rule modules found in src/')
  const inline = parts.join('\n')
  if (src.split('/*@games*/').length !== 2) throw new Error('src/client.src.js must contain /*@games*/ exactly once')
  return `// GENERATED by tools/build-client.mjs from src/client.src.js + src/games.js. Do not edit; edit src/ and run npm run build.\n` + src.replace('/*@games*/', () => inline)
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = path.join(root, 'lib', 'client.js')
  const built = buildClient()
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(out) ? fs.readFileSync(out, 'utf8').replace(/\r\n/g, '\n') : ''
    if (current !== built) {
      console.error('lib/client.js is out of date. Run: npm run build')
      process.exit(1)
    }
    console.log('lib/client.js is up to date')
  } else {
    fs.writeFileSync(out, built)
    console.log(`wrote lib/client.js (${built.length} bytes)`)
  }
}